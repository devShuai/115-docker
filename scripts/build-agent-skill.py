#!/usr/bin/env python3
"""Generate a self-contained skill from the canonical API docs and CLI."""
import argparse
import hashlib
import json
from pathlib import Path
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'runtime/downloader'))
import apidocs  # noqa: E402

NAME = '115-download'
SKILL = ROOT / 'skills' / NAME
MANIFEST = 'manifest.json'
FILES = ('SKILL.md', 'agents/openai.yaml', 'scripts/115dl.py', 'references/api.md', 'references/openapi.json')


def generated():
    guide = apidocs.agent_guide()
    guide = guide[:guide.index('## 安装 Agent Skill')] + guide[guide.index('## 安装与非交互调用'):]
    # The skill already contains its CLI; standalone-client installation belongs to the web guide.
    start = guide.index('## 安装与非交互调用')
    end = guide.index('全局参数必须放在子命令前。', start)
    guide = (guide[:start] + '## 本 skill 的调用方式\n\n'
             '使用 `python3 "$SKILL_DIR/scripts/115dl.py" --no-input --json COMMAND`；'
             '`$SKILL_DIR` 为本技能目录，下面示例也使用此路径。\n\n' + guide[end:])
    guide = guide.replace('115dl --json ', 'python3 "$SKILL_DIR/scripts/115dl.py" --no-input --json ')
    guide = guide.replace('115dl --no-input --json ', 'python3 "$SKILL_DIR/scripts/115dl.py" --no-input --json ')
    return {
        'scripts/115dl.py': (ROOT / 'runtime/downloader/cli.py').read_bytes(),
        'references/api.md': ('<!-- Generated by scripts/build-agent-skill.py; edit apidocs.py instead. -->\n' + guide).encode(),
        'references/openapi.json': (json.dumps(apidocs.openapi(), ensure_ascii=False, indent=2) + '\n').encode(),
    }


def build(check=False, archive=None):
    payload = generated()
    for name in FILES:
        if name not in payload:
            payload[name] = (SKILL / name).read_bytes()
    manifest = {'format': 1, 'name': NAME, 'files': {
        name: {'sha256': hashlib.sha256(payload[name]).hexdigest(), 'size': len(payload[name])} for name in FILES}}
    payload[MANIFEST] = (json.dumps(manifest, ensure_ascii=False, indent=2) + '\n').encode()
    for name, content in payload.items():
        destination = SKILL / name
        if check:
            if not destination.is_file() or destination.read_bytes() != content:
                raise ValueError(f'{destination.relative_to(ROOT)} is stale; run python3 scripts/build-agent-skill.py')
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(content)
    if archive:
        output = Path(archive)
        output.parent.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(output, 'w', zipfile.ZIP_DEFLATED) as zipped:
            for name, content in payload.items():
                info = zipfile.ZipInfo(NAME + '/' + name, date_time=(2026, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                info.external_attr = (0o100700 if name.startswith('scripts/') else 0o100600) << 16
                zipped.writestr(info, content)
    print('PASS: self-contained 115-download skill is synchronized' if check else 'Built: skills/115-download')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--zip', dest='archive', help='optional portable skill ZIP output')
    args = parser.parse_args()
    try:
        build(args.check, args.archive)
    except (OSError, ValueError) as error:
        parser.exit(1, str(error) + '\n')


if __name__ == '__main__':
    main()
